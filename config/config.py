"""
Central configuration for the Credit Card Fraud Detection Big Data project.

All paths are computed relative to the project root (the parent of this
config/ directory), so the project runs the same regardless of where it is
checked out. Settings that a student might want to change for their machine
(Mongo URI, Spark master, sample size) are grouped here instead of being
scattered/hardcoded across scripts.
"""

import os
from pathlib import Path

# ---------------------------------------------------------------------------
# Project paths
# ---------------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent

DATA_DIR = PROJECT_ROOT / "data"
RAW_DATA_DIR = DATA_DIR / "raw"
PROCESSED_DATA_DIR = DATA_DIR / "processed"

RESULTS_DIR = PROJECT_ROOT / "results"
METRICS_DIR = RESULTS_DIR / "metrics"
FIGURES_DIR = RESULTS_DIR / "figures"
MODELS_DIR = RESULTS_DIR / "models"

# Primary dataset file. Either the synthetic demo file generated by
# scripts/generate_synthetic_data.py, or a real Kaggle CSV placed here with
# the SAME column names (see docs/DATASET.md for the exact schema and the
# recommended real-world source).
RAW_TRANSACTIONS_FILE = RAW_DATA_DIR / "transactions.csv"
CLEANED_TRANSACTIONS_FILE = PROCESSED_DATA_DIR / "transactions_clean.parquet"
CLEANED_TRANSACTIONS_CSV = PROCESSED_DATA_DIR / "transactions_clean.csv"

# ---------------------------------------------------------------------------
# Canonical transaction schema
# ---------------------------------------------------------------------------
# Every downstream module (preprocessing, MapReduce, Hive, Spark, NoSQL,
# fraud detection) is written against these column names. This matches the
# Kaggle "Credit Card Transactions Fraud Detection Dataset" (Sparkov-style,
# by kartik2112) so the real dataset can be dropped in with no code changes.
TRANSACTION_ID_COL = "trans_num"
TIMESTAMP_COL = "trans_date_trans_time"
UNIX_TIME_COL = "unix_time"
CARD_NUM_COL = "cc_num"
MERCHANT_COL = "merchant"
CATEGORY_COL = "category"
AMOUNT_COL = "amt"
CUSTOMER_FIRST_COL = "first"
CUSTOMER_LAST_COL = "last"
GENDER_COL = "gender"
CITY_COL = "city"
STATE_COL = "state"
ZIP_COL = "zip"
LAT_COL = "lat"
LONG_COL = "long"
CITY_POP_COL = "city_pop"
JOB_COL = "job"
DOB_COL = "dob"
MERCH_LAT_COL = "merch_lat"
MERCH_LONG_COL = "merch_long"
LABEL_COL = "is_fraud"

# ---------------------------------------------------------------------------
# Synthetic data generation settings (used only when no real dataset present)
# ---------------------------------------------------------------------------
SYNTHETIC_NUM_TRANSACTIONS = int(os.environ.get("BDA_SYNTH_ROWS", 150_000))
SYNTHETIC_NUM_CUSTOMERS = 600
SYNTHETIC_NUM_MERCHANTS = 120
SYNTHETIC_FRAUD_RATE = 0.006  # ~0.6% fraud, realistic imbalance
SYNTHETIC_RANDOM_SEED = 42

# ---------------------------------------------------------------------------
# MongoDB settings
# ---------------------------------------------------------------------------
# If MONGO_URI is unset/unreachable, the nosql module transparently falls
# back to mongomock (an in-memory MongoDB-compatible store) so the project
# still runs with zero local installs. Set a real URI to demo against an
# actual MongoDB instance (local install or free-tier MongoDB Atlas).
MONGO_URI = os.environ.get("BDA_MONGO_URI", "mongodb://localhost:27017")
MONGO_DB_NAME = os.environ.get("BDA_MONGO_DB", "fraud_analytics")

# ---------------------------------------------------------------------------
# Spark settings
# ---------------------------------------------------------------------------
SPARK_MASTER = os.environ.get("BDA_SPARK_MASTER", "local[*]")
SPARK_APP_NAME = "CreditCardFraudAnalytics"

# ---------------------------------------------------------------------------
# ML settings
# ---------------------------------------------------------------------------
TRAIN_TEST_SPLIT_RATIO = 0.2
RANDOM_STATE = 42
HIGH_VALUE_THRESHOLD = 500.0  # amount (in dataset currency units) considered a "high-value" transaction

for _d in (RAW_DATA_DIR, PROCESSED_DATA_DIR, METRICS_DIR, FIGURES_DIR, MODELS_DIR):
    _d.mkdir(parents=True, exist_ok=True)
